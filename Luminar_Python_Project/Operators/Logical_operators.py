#Logical Operators
"""
AND- & --> both condition true
OR- |  --> one of the condition or both true
XOR- ^ --> both different condition
"""
num1,num2=2,4
print(num1&num2) #it will return 0

num3,num4=4,4
print(num3&num4) #it will return 4

print(6&5) #it will also return 4


